let language: Language = 'de';
export function setLanguage(l: Language) {
  language = l;
  document.documentElement.lang = l;
}
export function getLanguage() {
  return language;
}
export function t(key: string, params: Record<string, string | number> = {}) {
  let text = strings[key]?.[(['de', 'en', 'es', 'fr'] as Language[]).indexOf(language)] ?? key;
  for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
export function description(id: string, category: string, storage?: number) {
  if (id === 'farm') return t('farmingDesc');
  if (id === 'research') return t('researchHint');
  if (id === 'workshop') return t('craftingDesc');
  if (id === 'healer') return t('herbsDesc');
  if (id === 'market') return t('tradeDesc');
  if (storage) return t('storageDesc');
  return t(
    category === 'housing'
      ? 'housingDesc'
      : category === 'production'
        ? 'productionDesc'
        : category === 'defense'
          ? 'defenseBuildingDesc'
          : category === 'paths'
            ? 'pathDesc'
            : 'communityDesc',
  );
}
export function techName(id: string) {
  return t(id === 'defense' ? 'defenseTech' : id === 'bronze' ? 'bronzeTech' : id);
}
